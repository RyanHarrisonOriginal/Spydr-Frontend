import { describe, expect, it } from "vitest";
import { isAutoGeneratedTitle, realTitle } from "./titles";

describe("log titles", () => {
  it("treats blank and Untitled Node stamps as auto-generated", () => {
    expect(isAutoGeneratedTitle("")).toBe(true);
    expect(isAutoGeneratedTitle("  ")).toBe(true);
    expect(
      isAutoGeneratedTitle("Untitled Node - 2026-09-22-21:19:08")
    ).toBe(true);
    expect(isAutoGeneratedTitle("Untitled note")).toBe(true);
  });

  it("returns only real user titles", () => {
    expect(realTitle("Kickoff notes")).toBe("Kickoff notes");
    expect(realTitle("Untitled Node - 2026-09-22-21:19:08")).toBeNull();
    expect(realTitle("")).toBeNull();
  });
});
